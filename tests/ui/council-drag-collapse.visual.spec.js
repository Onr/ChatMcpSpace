const { test, expect } = require('@playwright/test');
const fs = require('fs');
const path = require('path');
const ejs = require('ejs');
const root = path.join(__dirname, '../..');
const dashboard = fs.readFileSync(path.join(root, 'public/js/dashboard.js'), 'utf8');
const source = dashboard.slice(dashboard.indexOf('function setupCouncilMinimize()'), dashboard.indexOf('function setupCouncilListResizeHandle()'));
for (const multi of [false, true]) test(`divider collapses and expands the actual dashboard (multi=${multi})`, async ({ page }) => {
  const locals = { agents: [], groups: [], encryptionSalt: '', isGoogleAuth: false, csrfToken: 'fixture', cspNonce: 'fixture', assetUrl: p => p, safeJsonForScript: JSON.stringify, user: { userId: 'fixture', displayName: 'Test', email: 'test@example.test' }, currentPath: '/dashboard' };
  const body = await ejs.renderFile(path.join(root, 'views/dashboard.ejs'), locals);
  let html = await ejs.renderFile(path.join(root, 'views/layout.ejs'), { ...locals, body });
  html = html.replace(/<script\b[^>]*>[\s\S]*?<\/script>/gi, '').replace(/<link\b[^>]*>/gi, '');
  html = html.replace('</head>', `<style>${['tailwind', 'style'].map(f => fs.readFileSync(path.join(root, `public/css/${f}.css`), 'utf8')).join('\n')}</style></head>`);
  await page.route('https://council.test/', route => route.fulfill({ contentType: 'text/html', body: html }));
  await page.setViewportSize({ width: 1440, height: 1000 });
  await page.goto('https://council.test/');
  await page.evaluate(({ source, multi }) => {
    const grid = document.querySelector('.dashboard-main-grid');
    grid.classList.toggle('dashboard-main-grid--multi-open', multi);
    window.MultiChatManager = { onPanelsChanged() {} };
    new Function('COUNCIL_SPLIT_STORAGE_KEY', 'isMobileListOnlyMode', source + '\nsetupCouncilMinimize(); setupCouncilResizeHandle();')('split', () => false);
  }, { source, multi });
  const handle = page.locator('#councilResizeHandle');
  const grid = page.locator('.dashboard-main-grid');
  const chamber = page.locator('.council-chamber');
  await expect(handle).toBeVisible();
  const bounds = await handle.boundingBox();
  const gridBounds = await grid.boundingBox();
  await page.mouse.move(bounds.x + bounds.width / 2, bounds.y + bounds.height / 2);
  await page.mouse.down();
  await page.mouse.move(gridBounds.x + (multi ? 270 : 320), bounds.y + bounds.height / 2, { steps: 8 });
  await page.mouse.up();
  await expect(grid).toHaveClass(/council-minimized/);
  await expect(handle).toBeHidden();
  await expect.poll(async () => (await chamber.boundingBox()).width).toBe(80);
  expect(await page.evaluate(() => localStorage.getItem('council_minimized'))).toBe('true');
  await page.locator('#maximizeCouncilBtn').click();
  await expect(grid).not.toHaveClass(/council-minimized/);
  await expect(handle).toBeVisible();
  await expect.poll(async () => (await chamber.boundingBox()).width).toBeGreaterThanOrEqual(multi ? 330 : 380);
  const restored = await handle.boundingBox();
  await page.mouse.move(restored.x + restored.width / 2, restored.y + restored.height / 2);
  await page.mouse.down();
  await page.mouse.move(gridBounds.x + 500, restored.y + restored.height / 2, { steps: 4 });
  await page.mouse.up();
  await expect(grid).not.toHaveClass(/council-minimized/);
  await expect.poll(async () => (await chamber.boundingBox()).width).toBeGreaterThan(multi ? 390 : 440);
});
